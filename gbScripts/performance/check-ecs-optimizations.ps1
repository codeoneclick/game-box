param([switch]$NavigationOnly,[ValidateSet('debug','release')][string]$Configuration='release')
$ErrorActionPreference='Stop'
$repoRoot=Split-Path -Parent (Split-Path -Parent $PSScriptRoot)
$vswhere=Join-Path ${env:ProgramFiles(x86)} 'Microsoft Visual Studio/Installer/vswhere.exe'
$vsRoot=& $vswhere -latest -products * -requires Microsoft.VisualStudio.Component.VC.Tools.x86.x64 -property installationPath
if(!$vsRoot){throw 'Visual Studio C++ tools were not found.'}
$vcvars=Join-Path $vsRoot 'VC/Auxiliary/Build/vcvars64.bat'
$output=Join-Path $repoRoot 'gbDemo/output/ecs-check'
New-Item -ItemType Directory -Path $output -Force | Out-Null
function Invoke-Probe($name,$sources,$includeOptions,$linkOptions,$runtimePath='') {
    $quotedSources=($sources | ForEach-Object {'"'+(Join-Path $repoRoot $_)+'"'}) -join ' '
    $exe=Join-Path $output ($name+'.exe')
    $command=@(
        ('@set PATH={0};{1};%PATH%' -f (Split-Path -Parent $vswhere),$runtimePath),
        ('@call "{0}" >nul' -f $vcvars),
        ('@cd /d "{0}"' -f $output),
        ('@cl /nologo /EHsc /std:c++14 /Gy {0} {1} /Fe:"{2}" {3}' -f $includeOptions,$quotedSources,$exe,$linkOptions),
        '@if errorlevel 1 exit /b 1',
        ('@"{0}"' -f $exe)
    )
    $script=Join-Path $output ($name+'.cmd')
    Set-Content -LiteralPath $script -Value $command -Encoding ASCII
    & cmd /c $script
    if($LASTEXITCODE -ne 0){throw "$name failed with exit code $LASTEXITCODE"}
}
$demoInclude='/I"'+(Join-Path $repoRoot 'gbDemo/sources')+'"'
Invoke-Probe 'ecs_navigation' @('gbScripts/performance/check_ecs_navigation.cpp','gbDemo/sources/resident_navigation.cpp','gbDemo/sources/resident_behavior.cpp') $demoInclude ''
Invoke-Probe 'resident_cpu' @('gbScripts/check_island_resident.cpp','gbDemo/sources/terrain_generator.cpp','gbDemo/sources/terrain_mesh_builder.cpp','gbDemo/sources/resident_navigation.cpp','gbDemo/sources/resident_behavior.cpp') ($demoInclude+' /O2') ''
if(!$NavigationOnly){
    # Link the available matching Windows engine target; this script does not build/run the demo.
    $core=Join-Path $repoRoot "gbCore/output/$Configuration/x64/gb_core.lib"
    if(!(Test-Path -LiteralPath $core)){throw "Build the $Configuration-client x64 demo target before the core probe."}
    $sdk=$env:VULKAN_SDK
    if(!$sdk){$sdk=(Get-ChildItem 'C:/VulkanSDK' -Directory | Sort-Object Name -Descending | Select-Object -First 1).FullName}
    if(!$sdk){throw 'Vulkan SDK was not found.'}
    $coreInclude='/MT /O2 /D_ITERATOR_DEBUG_LEVEL=0 /D_HAS_EXCEPTIONS=0 /D__WINOS__ /DWIN32_LEAN_AND_MEAN /D__IS_CONFIGURATION_MUTABLE__=1'
    foreach($path in @('gbCore/sources','gbCore/libraries','gbCore/autogenerated','gbCore/libraries/zlib-1.2.8','gbCore/libraries/freetype2/include')){$coreInclude+=' /I"'+(Join-Path $repoRoot $path)+'"'}
    $coreInclude+=' /I"'+(Join-Path $sdk 'Include')+'"'
    $link='/link /OPT:REF "'+$core+'" /LIBPATH:"'+(Join-Path $sdk 'Lib')+'" vulkan-1.lib shaderc_shared.lib opengl32.lib user32.lib gdi32.lib'
    Invoke-Probe 'ecs_core' @('gbScripts/performance/check_ecs_core.cpp') $coreInclude $link (Join-Path $sdk 'Bin')
}
